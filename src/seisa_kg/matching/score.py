"""SUMMARY: Scores the matching hand-check (D-107): Bruno's answers in
eval/matching-sample.csv against the code's hidden answers in
data/interim/matching-sample-key.json, and writes docs/matching-eval.md.

What it reports:
- agreement: the share of names where Bruno and the code chose the same outcome;
- precision of links: of the names the code linked (sameEntityAs or
  refersToGroup), how many Bruno links the same way, to the same target;
- recall of links: of the names Bruno links, how many the code linked the same way.
The sample over-represents rare outcomes (stratified), so each row is weighted by
its group's real size divided by how many of that group were sampled. Both the
weighted and the plain (unweighted) numbers are shown.

Honesty note: on 21 Oct many rows were judged with Claude's help, so each row is
put in one of three groups (from the session record, see WHO below) and agreement
is reported per group as well.

Run with: uv run python -m seisa_kg.matching.score
"""

# Reads the hand-check sheet.
import csv
# Reads the hidden key.
import json
# Counts outcomes for the tables.
from collections import Counter
# A tidy way of working with file paths.
from pathlib import Path

# The project's root folder.
ROOT = Path(__file__).resolve().parents[3]
# Bruno's answers.
SHEET = ROOT / "eval" / "matching-sample.csv"
# The code's answers and the group sizes, written by sample.py.
KEY = ROOT / "data" / "interim" / "matching-sample-key.json"
# The report this writes.
REPORT = ROOT / "docs" / "matching-eval.md"
# The two outcomes that are links.
LINKS = {"sameEntityAs", "refersToGroup"}
# Who judged each row on 21 Oct, from the session record (D-119):
# "own" = Bruno gave the outcome before Claude commented; "guided" = Claude explained or
# corrected first, then Bruno chose; "claude" = Bruno accepted Claude's suggested answer.
WHO = {**{i: "own" for i in (3, 7, 10, 11, 15, 16, 20, 22, 23, 35, 36, 38)},
       **{i: "guided" for i in (1, 2, 4, 5, 6, 8, 9, 12, 13, 14, 17, 18, 19, 21, 29, 30, 37, 39, 40, 43, 44)},
       **{i: "claude" for i in (24, 25, 26, 27, 28, 31, 32, 33, 34, 41, 42, 45, 46, 47, 48, 49, 50)}}


# Does Bruno's target text name the same thing as the code's target list?
def same_target(outcome: str, bruno: str, code: list[str]) -> bool:
    # A group link: Bruno writes "hg", the code writes "ex:sponsor/hg".
    if outcome == "refersToGroup":
        # Same sponsor.
        return [f"ex:sponsor/{bruno.strip().lower()}"] == code
    # A company link: the code's id (lei:… or ch:…) must appear in Bruno's text.
    return len(code) == 1 and code[0] in bruno


# Work out every number and write the report.
def main() -> None:
    # Bruno's rows, by id.
    sheet = {int(r["id"]): r for r in csv.DictReader(SHEET.open(encoding="utf-8"))}
    # The key: group sizes, quotas and the code's rows.
    key = json.loads(KEY.read_text(encoding="utf-8"))
    # The code's rows, by id.
    code = {r["id"]: r for r in key["rows"]}
    # Each row's weight: its group's real size / how many of that group were sampled.
    weight = {i: key["group_sizes"][c["outcome"]] / key["quotas"][c["outcome"]] for i, c in code.items()}
    # One line per row: id, name, role, both outcomes, whether they agree, and whether the link matches.
    lines = []
    # Each row.
    for i in sorted(sheet):
        # Bruno's and the code's outcome.
        b, c = sheet[i]["your_outcome"], code[i]["outcome"]
        # Same outcome, and (for a link) the same target too.
        link_match = b == c and b in LINKS and same_target(b, sheet[i]["your_target"], code[i]["to"])
        # Keep the row's facts.
        lines.append({"id": i, "name": sheet[i]["name"], "role": sheet[i]["role"], "bruno": b, "code": c,
                      "agree": b == c, "link_match": link_match, "w": weight[i], "who": WHO[i],
                      "note": sheet[i]["your_note"], "why": code[i]["why"]})
    # A weighted share: sum of weights where the test holds / sum of weights in the set.
    share = lambda rows, test, w=True: (sum(r["w"] if w else 1 for r in rows if test(r)) /
                                        sum(r["w"] if w else 1 for r in rows)) if rows else float("nan")
    # Rows the code linked, and rows Bruno linked.
    code_links, bruno_links = [r for r in lines if r["code"] in LINKS], [r for r in lines if r["bruno"] in LINKS]
    # The headline numbers, weighted and plain.
    nums = {
        "agreement": (share(lines, lambda r: r["agree"]), share(lines, lambda r: r["agree"], False)),
        "precision": (share(code_links, lambda r: r["link_match"]), share(code_links, lambda r: r["link_match"], False)),
        "recall": (share(bruno_links, lambda r: r["link_match"]), share(bruno_links, lambda r: r["link_match"], False)),
    }
    # The report, line by line.
    out = ["# Matching hand-check: results (generated by `uv run python -m seisa_kg.matching.score`)", "",
           f"50 names, sampled by the code's outcome (D-107). Weighted numbers scale each row by its group's real size "
           f"(184 distinct names in all), so they estimate the whole list; plain numbers count the 50 rows equally.", "",
           "| Measure | Weighted | Plain | What it means |", "|---|---|---|---|",
           f"| Agreement | {nums['agreement'][0]:.0%} | {nums['agreement'][1]:.0%} | same outcome as the code |",
           f"| Precision (links) | {nums['precision'][0]:.0%} | {nums['precision'][1]:.0%} | of the code's {len(code_links)} links, the share Bruno links the same way |",
           f"| Recall (links) | {nums['recall'][0]:.0%} | {nums['recall'][1]:.0%} | of Bruno's {len(bruno_links)} links, the share the code made the same way |",
           "", "## Agreement by who judged the row (honesty check)", "",
           "| Group | Rows | Agreement (plain) |", "|---|---|---|"]
    # One line per group.
    for g, label in (("own", "Bruno alone"), ("guided", "Bruno, after Claude explained or corrected"), ("claude", "Claude's suggestion, accepted")):
        # The group's rows.
        rows = [r for r in lines if r["who"] == g]
        # Its line.
        out.append(f"| {label} | {len(rows)} | {share(rows, lambda r: r['agree'], False):.0%} |")
    # The confusion table: code's outcome (rows) vs Bruno's (columns).
    kinds = ["sameEntityAs", "refersToGroup", "ambiguous", "news-only", "out-of-scope", "non-entity", "unresolved"]
    # Its heading.
    out += ["", "## Code (rows) vs Bruno (columns)", "", "| code \\ Bruno | " + " | ".join(kinds) + " |",
            "|---" * (len(kinds) + 1) + "|"]
    # Each pair's count.
    pairs = Counter((r["code"], r["bruno"]) for r in lines)
    # One line per code outcome.
    for k in kinds:
        # The counts, with blanks for zero.
        out.append(f"| **{k}** | " + " | ".join(str(pairs[(k, b)] or "") for b in kinds) + " |")
    # Every disagreement, with both reasons.
    out += ["", "## Every disagreement", "", "| # | Name (role) | Code says | Bruno says | Code's reason | Bruno's note | Judged |",
            "|---|---|---|---|---|---|---|"]
    # Each row where they differ (or link the same way to different targets).
    for r in lines:
        # Skip full agreements.
        if r["agree"] and (r["bruno"] not in LINKS or r["link_match"]):
            # Next row.
            continue
        # Its line.
        out.append(f"| {r['id']} | {r['name']} ({r['role']}) | {r['code']} | {r['bruno']} | {r['why']} | {r['note']} | {r['who']} |")
    # Save the report.
    REPORT.write_text("\n".join(out) + "\n", encoding="utf-8")
    # Show it.
    print("\n".join(out))


# Run main() when the file is run directly.
if __name__ == "__main__":
    # Go.
    main()
