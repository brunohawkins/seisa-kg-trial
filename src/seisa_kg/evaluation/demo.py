"""SUMMARY: A demonstration that the scorer gives graded, sensible scores
(D-059 to D-061), before any real candidate answers exist.

For each question's reference answer it builds deliberately damaged copies,
one per typical mistake, and scores each one:
- a perfect copy (should score 1);
- two items missed; one item invented; every count 10% low (if the question has counts);
- no sources cited; each item citing another item's source;
- "not available" (giving up).
The results go to docs/scoring-demo.md.

Run it with:  make score-demo
"""

# Reads the saved reference answers.
import json
# A tidy way of working with file and folder paths.
from pathlib import Path

# The scorer, and how it recognises a source (a web address, or one of our source-record ids).
from seisa_kg.evaluation.score import OUR_DOMAIN, SOURCE_ID, SOURCE_IRI, URL, score

# The project's top folder: this file's folder, then up three levels (evaluation → seisa_kg → src → project).
PROJECT_ROOT = Path(__file__).resolve().parents[3]
# Where the reference answers are saved (by `make query`).
ANSWERS_DIR = PROJECT_ROOT / "data" / "output" / "answers" / "rdf"
# The report.
REPORT_PATH = PROJECT_ROOT / "docs" / "scoring-demo.md"


# Build the damaged copies of one reference answer: a list of (name, candidate).
def variants(ref: dict) -> list[tuple[str, dict]]:
    # The reference rows.
    rows = ref["rows"]
    # The column holding a count, if the question has one.
    value = ref.get("VALUE")
    # The columns that hold sources: any column where some cell cites a record (Q5 and Q10 have two, with other names).
    cited = lambda text: SOURCE_ID.search(text) or SOURCE_IRI.search(text) or any(not u.startswith(OUR_DOMAIN) for u in URL.findall(text))
    # Those columns, in order.
    src_cols = [c for c in ref["columns"] if any(cited(r[c]) for r in rows)]
    # A made-up row that matches nothing, citing a made-up source.
    fake = {"name": "Invented Holdings Ltd", "sources": "https://api.gleif.org/api/v1/lei-records/INVENTED"}
    # The list of copies, each with a plain-English name.
    out = [("Perfect copy", {"rows": rows}),
           # The last two items left out.
           ("Two items missed", {"rows": rows[:-2]}),
           # One extra, invented item.
           ("One item invented", {"rows": rows + [fake]})]
    # Only for questions with counts: every count 10% low, rounded.
    if value:
        # Copy each row with its count lowered.
        out.append(("Every count 10% low", {"rows": [dict(r, **{value: str(round(float(r[value]) * 0.9))}) for r in rows]}))
    # The right items with the sources column removed.
    out.append(("No sources cited", {"rows": [{k: v for k, v in r.items() if k not in src_cols} for r in rows]}))
    # Each item cites the next item's sources (the last cites the first's).
    out.append(("Sources swapped between items", {"rows": [dict(r, **{c: rows[(i + 1) % len(rows)][c] for c in src_cols}) for i, r in enumerate(rows)]}))
    # Giving up.
    out.append(("Says 'not available'", {"not_available": True}))
    # Hand back the copies.
    return out


# Score every damaged copy of every question and write the report.
def main() -> None:
    # The report's opening lines.
    L = ["# Scoring demonstration (generated by `make score-demo`; do not edit by hand)", "",
         # What this shows.
         "Each question's reference answer is damaged on purpose, one typical mistake at a time, and scored (D-059 to D-061).",
         # How to read the columns.
         "Correctness = F1 of precision and recall; citation = F1 of support and coverage; overall = their average.", ""]
    # Each saved reference answer, in name order.
    for path in sorted(ANSWERS_DIR.glob("*.json")):
        # Read it.
        ref = json.loads(path.read_text(encoding="utf-8"))
        # The section heading and the question.
        L += [f"## {path.stem}", "", f"*{ref.get('QUESTION', '')}* ({len(ref['rows'])} reference items)", "",
              # The table header.
              "| Candidate | Correctness | Precision | Recall | Citation | Support | Coverage | **Overall** | What went wrong |",
              # The table's dividing line.
              "|---|---|---|---|---|---|---|---|---|"]
        # Each damaged copy.
        for name, cand in variants(ref):
            # Score it.
            s = score(ref, cand)
            # The non-zero error counts, as short text.
            wrong = ", ".join(f"{k.replace('_', ' ')}: {v}" for k, v in s["errors"].items() if v) or "nothing"
            # One table row.
            L.append(f"| {name} | {s['correctness']} | {s['precision']} | {s['recall']} | {s['citation']} | "
                     # The rest of the row.
                     f"{s['support']} | {s['coverage']} | **{s['overall']}** | {wrong} |")
        # A blank line before the next question.
        L.append("")
    # Save the report.
    REPORT_PATH.write_text("\n".join(L), encoding="utf-8")
    # Say where it is.
    print(f"Report: {REPORT_PATH.relative_to(PROJECT_ROOT)}")


# Run main() when this file is run directly, not when it is imported.
if __name__ == "__main__":
    # Start.
    main()
