from pathlib import Path

# The RDF database.
import pyoxigraph as ox

# The connection to Neo4j.
from seisa_kg.lpg.build import connect
# The RDF graph's file and our short prefixes.
from seisa_kg.rdf.build import OUTPUT_PATH, PREFIXES

# The project's top folder.
PROJECT_ROOT = Path(__file__).resolve().parents[3]
# Where the comparison's files go.
OUT_DIR = PROJECT_ROOT / "data" / "output" / "comparison"

# The RDF "how it works" notes (hand-written, from docs/schema/rdf-schema.md).
RDF_NOTES = """## How it works
- Every fact is a triple. Its source is on a note about it (RDF-star):
  `?note rdf:reifies <<( ?s ?p ?o )>> ; prov:wasDerivedFrom ?record .`
  A registry record has a web address: `?record ex:url ?url ; ex:retrievedAt ?fetched .`
  A news fact's record is the sentence it came from, e.g. `src:news/hg-06/s03` (cite that id).
- A fact we made by a rule (scope, matching, tidy keys) has `prov:wasGeneratedBy ex:rule/D-0xx` on its note instead.
- Details of a fact (start date, status, quote, language) are extra properties on its note, not on the subject.
- Which companies belong to a sponsor: a scope decision node,
  `?d a ex:ScopeDecision ; ex:entity ?company ; ex:sponsor ?sponsor ; ex:verdict ex:In .`
  The sponsors are `<https://seisa-kg.example/def/sponsor/hg>`, `.../apax`, `.../bridgepoint`, each with an `rdfs:label` ("Hg", "Apax", "Bridgepoint").
- Names containing "/" (e.g. `ex:sponsor/apax`) must be written as full IRIs in angle brackets, or with a `\\/` escape.
- GLEIF companies are `lei:<LEI>`; Companies House companies are `ch:<number>`; `?lei ex:sameEntityAs ?ch` links the two records of one company.
- News: a `ex:Deal` or `ex:FundClose` has `ex:announcedIn ?release`; `?release ex:publishedBy ?sponsor ; ex:publishedOn ?date`.
  Each name in a deal (buyer, seller, target, fund, sponsor, adviser) has a `ex:Match` node (`ex:buyerMatch`, ...) with `ex:nameAsWritten`, `ex:outcome`,
  and a link `ex:sameEntityAs` (one company) or `ex:refersToGroup` (a sponsor).
"""

# The Neo4j "how it works" notes (hand-written, from docs/schema/lpg-schema.md).
LPG_NOTES = """## How it works
- Every node has an `id` property: its name in our data, e.g. `"lei:213800KFNMVI8PDZX472"`, `"ex:sponsor/apax"`, `"src:news/hg-06/s03"`.
- A relationship's source is a property on it: `record` (a SourceRecord's id) for a source, or `rule` (e.g. "D-025") for our own judgement.
  Fetch the record with `MATCH (rec:SourceRecord {id: r.record})`; a registry record has `url` and `retrievedAt`.
- A node's values have their sources on receipts: `(n)-[rc:DERIVED_FROM]->(rec:SourceRecord)` (or `GENERATED_BY` to a `:Rule`).
  `rc.properties` lists the property names it vouches for, and `rc.values` their values, in the same order (properties[i] goes with values[i]).
  A news fact's record is the sentence it came from, e.g. `src:news/hg-06/s03` (cite that id).
- Some properties are lists on every node of that label (marked "list" below): use `UNWIND` or `IN`.
- Which companies belong to a sponsor: `(c:Company)-[s:IN_SCOPE_OF]->(:Sponsor {id: "ex:sponsor/apax"})` with `s.verdict = "In"`.
  Sponsors have `label` "Hg", "Apax", "Bridgepoint".
- A company found in both registers has two nodes, `:Company:Gleif` and `:Company:CompaniesHouse`, linked by `SAME_ENTITY_AS`.
- News: `(d:Deal)-[:ANNOUNCED_IN]->(r:Release)-[:PUBLISHED_BY]->(:Sponsor)`; `r.publishedOn` is a date.
  Each name in a deal has a `:Match` node (`BUYER_MATCH`, `SELLER_MATCH`, ...) with `nameAsWritten`, `outcome`,
  and a link `SAME_ENTITY_AS` (one company) or `REFERS_TO_GROUP` (a sponsor).
"""

# The worked example for SPARQL: not one of the 8 test questions.
RDF_EXAMPLE = """## Worked example (not a test question)
Question: What is Bridgepoint Group plc's legal name according to GLEIF, and which records state it?
```sparql
PREFIX rdf:  <http://www.w3.org/1999/02/22-rdf-syntax-ns#>
PREFIX prov: <http://www.w3.org/ns/prov#>
PREFIX ex:   <https://seisa-kg.example/def/>
PREFIX lei:  <https://seisa-kg.example/lei/>
SELECT ?name (GROUP_CONCAT(DISTINCT ?url; SEPARATOR=" ") AS ?sources)
WHERE {
  lei:213800KFNMVI8PDZX472 ex:legalName ?name .
  ?note rdf:reifies <<( lei:213800KFNMVI8PDZX472 ex:legalName ?name )>> ; prov:wasDerivedFrom ?record .
  ?record ex:url ?url .
}
GROUP BY ?name
```
"""

# The same worked example in Cypher.
LPG_EXAMPLE = """## Worked example (not a test question)
Question: What is Bridgepoint Group plc's legal name according to GLEIF, and which records state it?
```cypher
MATCH (c:Company {id: "lei:213800KFNMVI8PDZX472"})-[rc:DERIVED_FROM]->(rec:SourceRecord)
WHERE "legalName" IN rc.properties
RETURN c.legalName AS name, collect(DISTINCT rec.url) AS sources
```
"""


# Write a short name for an RDF term: our prefix form if we have one.
def short(term) -> str:
    # The term's text.
    text = term.value
    # Each prefix (longest address first, so ex:sponsor/... isn't mistaken for something shorter).
    for prefix, base in sorted(PREFIXES.items(), key=lambda kv: -len(kv[1])):
        # Its address.
        if text.startswith(base):
            # The short form.
            return f"{prefix}:{text[len(base):]}"
    # Anything else as it is.
    return text


# The RDF phrasebook: prefixes, types, and every predicate with what it links.
def rdf_phrasebook() -> str:
    # Load the graph.
    store = ox.Store()
    # From the saved file.
    store.bulk_load(path=str(OUTPUT_PATH), format=ox.RdfFormat.TURTLE)
    # The opening and the prefixes.
    L = ["# RDF phrasebook (generated from data/output/graph.ttl)", "", "## Prefixes", ""]
    # One line per prefix.
    L += [f"PREFIX {p}: <{b}>" for p, b in PREFIXES.items()] + [""]
    # Every type and how many things have it.
    L += ["## Types (how many things of each)", ""]
    # Count per type.
    for r in store.query("SELECT ?t (COUNT(DISTINCT ?s) AS ?n) WHERE { ?s a ?t } GROUP BY ?t ORDER BY DESC(?n)"):
        # One line per type.
        L.append(f"- {short(r['t'])} ({r['n'].value})")
    # Every predicate: on what kind of subject, pointing at what, how often, and one example object.
    L += ["", "## Predicates (subject type -> object type or value kind; count; example)", ""]
    # The query: subject type (or "note" for a blank note), object type (or the value's datatype), count, one example.
    q = """SELECT ?p ?st ?ot (COUNT(*) AS ?n) (SAMPLE(?o) AS ?ex) WHERE {
             ?s ?p ?o . FILTER (?p != <http://www.w3.org/1999/02/22-rdf-syntax-ns#type>)
             OPTIONAL { ?s a ?st0 } OPTIONAL { ?o a ?ot0 }
             BIND (COALESCE(?st0, IF(isBLANK(?s), "note", "untyped")) AS ?st)
             BIND (COALESCE(?ot0, IF(isLITERAL(?o), DATATYPE(?o), IF(isTRIPLE(?o), "quoted triple", "untyped"))) AS ?ot)
           } GROUP BY ?p ?st ?ot ORDER BY ?p ?st"""
    # One line per predicate, subject type and object kind.
    for r in store.query(q):
        # The example object, cut short.
        ex = r["ex"]
        # A quoted triple has no simple text; say so.
        example = "<<( ... )>>" if isinstance(ex, ox.Triple) else short(ex)[:50]
        # The subject and object kinds, shortened.
        st, ot = (short(r[k]) if isinstance(r[k], ox.NamedNode) else r[k].value for k in ("st", "ot"))
        # The line.
        L.append(f"- {short(r['p'])}: {st} -> {ot} ({r['n'].value}; e.g. {example})")
    # The notes and the example.
    return "\n".join(L) + "\n\n" + RDF_NOTES + "\n" + RDF_EXAMPLE


# The Neo4j phrasebook: labels, properties (lists marked), and every relationship type with what it links.
def lpg_phrasebook() -> str:
    # The connection.
    driver = connect()
    # The opening.
    L = ["# Neo4j phrasebook (generated from the database)", "", "## Labels (how many nodes of each)", ""]
    # Count per label.
    for r in driver.execute_query("MATCH (n) UNWIND labels(n) AS l RETURN l, count(*) AS n ORDER BY n DESC").records:
        # One line per label.
        L.append(f"- :{r['l']} ({r['n']})")
    # Every property, per set of labels, with its types (Neo4j's own schema description).
    L += ["", "## Node properties (labels: property: types)", ""]
    # Neo4j's built-in schema procedure.
    for r in driver.execute_query("CALL db.schema.nodeTypeProperties() YIELD nodeLabels, propertyName, propertyTypes "
                                  "RETURN nodeLabels, propertyName, propertyTypes ORDER BY nodeLabels, propertyName").records:
        # A list property is marked as such.
        types = ", ".join(t.replace("StringArray", "list of String").replace("Array", " list") for t in r["propertyTypes"])
        # One line.
        L.append(f"- :{':'.join(r['nodeLabels'])} .{r['propertyName']}: {types}")
    # Every relationship type: from which labels to which, and how often.
    L += ["", "## Relationships (from -> to; count; properties)", ""]
    # Relationship properties, per type.
    props = {}
    # Neo4j's built-in schema procedure for relationships.
    for r in driver.execute_query("CALL db.schema.relTypeProperties() YIELD relType, propertyName RETURN relType, propertyName").records:
        # Collect the property names per type (relType looks like ":`FUND_MANAGED_BY`").
        props.setdefault(r["relType"].strip(":`"), set()).add(r["propertyName"])
    # Each type with the first label of each end.
    for r in driver.execute_query("MATCH (a)-[r]->(b) RETURN type(r) AS t, labels(a)[0] AS a, labels(b)[0] AS b, count(*) AS n "
                                  "ORDER BY t, n DESC").records:
        # Its properties, if any.
        p = ", ".join(sorted(x for x in props.get(r["t"], set()) if x))
        # One line.
        L.append(f"- (:{r['a']})-[:{r['t']}]->(:{r['b']}) ({r['n']}){'; ' + p if p else ''}")
    # Close the connection.
    driver.close()
    # The notes and the example.
    return "\n".join(L) + "\n\n" + LPG_NOTES + "\n" + LPG_EXAMPLE


# Write both phrasebooks.
def main() -> None:
    # Make sure the folder exists.
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    # The RDF one.
    (OUT_DIR / "phrasebook-rdf.md").write_text(rdf_phrasebook(), encoding="utf-8")
    # The Neo4j one.
    (OUT_DIR / "phrasebook-lpg.md").write_text(lpg_phrasebook(), encoding="utf-8")
    # Say where they are.
    print(f"Phrasebooks: {OUT_DIR.relative_to(PROJECT_ROOT)}/phrasebook-rdf.md, phrasebook-lpg.md")


# Run main() when this file is run directly.
if __name__ == "__main__":
    # Go.
    main()
