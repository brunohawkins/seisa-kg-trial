"""SUMMARY: Builds the two "phrasebooks" the LLM gets for text-to-SPARQL and
text-to-Cypher (D-124, decision 2): a description of each graph, generated by
code from the graph itself so it can never drift from what is really there,
plus a short hand-written "how it works" section and one worked example query.

Both phrasebooks give the same level of help: every type or label with its
count, every predicate or relationship with what it links, every property, how
sources work, and how scope works. Neither contains any of the 8 test questions.

Outputs (read by compare.py, and by Bruno):
- data/output/comparison/phrasebook-rdf.md
- data/output/comparison/phrasebook-lpg.md

Run with: uv run python -m seisa_kg.comparison.phrasebook   (Neo4j must be running)
"""

